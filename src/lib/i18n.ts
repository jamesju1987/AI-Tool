/** English lives at the root, Chinese under /zh (PRD §0). */
export function href(locale: Locale, path: string) {
  const p = path.startsWith("/") ? path : `/${path}`;
  if (locale === "en") return p;
  return p === "/" ? "/zh" : `/zh${p}`;
}

